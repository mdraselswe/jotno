def uid(*parts: str) -> str:
    return str(uuid.uuid5(NS, "/".join(parts)))


def q(v) -> str:
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


lines: list[str] = ["-- Demo data (generated by scripts/seed/gen_demo_seed.py). Remove with `pnpm db:clear-demo`.", ""]


def auth_user(user_id: str, email: str, name: str) -> None:
    lines.append(
        "insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at, "
        "raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token, recovery_token, "
        "email_change_token_new, email_change) values ("
        f"'00000000-0000-0000-0000-000000000000', {q(user_id)}, 'authenticated', 'authenticated', {q(email)}, "
        "extensions.crypt('jotno-demo-password', extensions.gen_salt('bf')), now(), "
        "'{\"provider\":\"email\",\"providers\":[\"email\"]}', "
        f"{q('{\"full_name\":\"' + name + '\"}')}, now(), now(), '', '', '', '') on conflict (id) do nothing;"
    )
    lines.append(
        "insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at) values ("
        f"{q(user_id)}, {q(user_id)}, {q(user_id)}, "
        f"{q('{\"sub\":\"' + user_id + '\",\"email\":\"' + email + '\",\"email_verified\":true}')}, 'email', now(), now(), now()) "
        "on conflict do nothing;"
    )


